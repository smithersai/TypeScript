package main

// The decision snapshot: what the resolver decides at every lambda, block,
// and by-name argument of the repository's .vibe files, over a table.
// scripts/check-forms-table.sh fails when it differs from a fresh run, and
// --write refuses to record a decision that moved at a site the snapshot
// already has unless forms_decisions_approved.txt names the move. A table
// regeneration therefore shows its user-visible effect as reviewed lines,
// not as an opaque table diff.

import (
	"bufio"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/microsoft/TypeScript/tsc/internal/ast"
	"github.com/microsoft/TypeScript/tsc/internal/core"
	"github.com/microsoft/TypeScript/tsc/internal/parser"
	"github.com/microsoft/TypeScript/tsc/internal/scanner"
	"github.com/microsoft/TypeScript/tsc/internal/tspath"
	"github.com/microsoft/TypeScript/tsc/internal/vibelangmapper"
)

// decisionRoots are the directories whose .vibe files the snapshot
// covers, relative to the repository root. packages/ts-mapper holds copies.
var decisionRoots = []string{"typescript/vibelang", "examples", "templates"}

// decisionLines returns the snapshot's lines, sorted: one per decision,
// "path:line:col kind result provenance", where kind is lambda, block, or
// byname, and result is the form (a block's appended/form), or choice
// when the user must write the form.
func decisionLines(repo string, table *vibelangmapper.Table) ([]string, error) {
	var files []string
	for _, root := range decisionRoots {
		err := filepath.WalkDir(filepath.Join(repo, root), func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				if os.IsNotExist(err) {
					return nil
				}
				return err
			}
			// out/ holds build and test output, such as the projects noemit-on-error writes; no source lives there.
			if d.IsDir() && (d.Name() == "node_modules" || d.Name() == "out" || strings.HasPrefix(d.Name(), ".")) {
				return filepath.SkipDir
			}
			if !d.IsDir() && strings.HasSuffix(path, ".vibe") {
				files = append(files, path)
			}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(files)
	var lines []string
	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		rel, _ := filepath.Rel(repo, path)
		rel = filepath.ToSlash(rel)
		text := string(data)
		abs, _ := filepath.Abs(path)
		file := parser.ParseSourceFile(ast.SourceFileParseOptions{FileName: tspath.RootedFilePathFromAbsolute(filepath.ToSlash(abs))}, text, core.ScriptKindTS)
		r := vibelangmapper.NewResolver(file, table)
		site := func(n *ast.Node) string {
			pos := scanner.SkipTrivia(text, n.Pos())
			line, col := 1, 1
			for _, c := range text[:pos] {
				if c == '\n' {
					line, col = line+1, 1
				} else {
					col++
				}
			}
			return fmt.Sprintf("%s:%d:%d", rel, line, col)
		}
		var visit func(n *ast.Node) bool
		visit = func(n *ast.Node) bool {
			isLambda := n.Kind == ast.KindArrowFunction || n.Kind == ast.KindFunctionExpression ||
				n.Kind == ast.KindMethodDeclaration && n.Parent != nil && n.Parent.Kind == ast.KindObjectLiteralExpression
			if isLambda {
				d := r.Lambda(n)
				kind, result := "lambda", d.Form.String()
				if d.Block {
					// A block is always its call's last argument (D376); the
					// snapshot keeps the placement D188 used to vary.
					kind, result = "block", "appended/"+d.Form.String()
				}
				if d.Choice != nil {
					result = "choice"
				}
				lines = append(lines, site(n)+" "+kind+" "+result+" "+d.Provenance.String())
			} else if n.Parent != nil && ast.IsExpression(n) {
				if d := r.Argument(n); d.ByName {
					lines = append(lines, site(n)+" byname program "+d.Provenance.String())
				}
			}
			n.ForEachChild(visit)
			return false
		}
		file.AsNode().ForEachChild(visit)
	}
	sort.Strings(lines)
	return lines, nil
}

// writeLines writes lines, one per line, after a header comment.
func writeLines(path string, lines []string) error {
	var b strings.Builder
	b.WriteString("# generated by " + Command + "; do not edit. Approve moved decisions in forms_decisions_approved.txt.\n")
	for _, l := range lines {
		b.WriteString(l)
		b.WriteByte('\n')
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// readLines reads a snapshot or an approvals file, skipping comments.
func readLines(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	defer f.Close()
	var out []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if l := strings.TrimSpace(sc.Text()); l != "" && !strings.HasPrefix(l, "#") {
			out = append(out, l)
		}
	}
	return out, sc.Err()
}

// unapprovedMoves returns the decisions that moved between previous and
// next at a site both snapshots have, which no approval line names. An
// approval line is "site kind: old -> new", optionally followed by
// " # reason".
func unapprovedMoves(previous, next, approvals []string) []string {
	parse := func(lines []string) map[string]string {
		m := map[string]string{}
		for _, l := range lines {
			site, rest, _ := strings.Cut(l, " ")
			kind, result, _ := strings.Cut(rest, " ")
			m[site+" "+kind] = result
		}
		return m
	}
	before, after := parse(previous), parse(next)
	approved := map[string]bool{}
	for _, a := range approvals {
		a, _, _ = strings.Cut(a, " #")
		approved[strings.Join(strings.Fields(a), " ")] = true
	}
	var moved []string
	for key, old := range before {
		now, ok := after[key]
		if !ok || now == old {
			continue
		}
		entry := key + ": " + old + " -> " + now
		if !approved[strings.Join(strings.Fields(entry), " ")] {
			moved = append(moved, entry)
		}
	}
	sort.Strings(moved)
	return moved
}
